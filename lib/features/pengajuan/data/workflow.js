function isDraftSubmission(body = {}) {
    return body.is_draft === true || body.save_as_draft === true || body.mode === 'draft';
}

// Legacy applications may not yet contain the full form or survey results.
function afterVerification(hasCreditData) {
    return hasCreditData ? WORKFLOW_NEXT_STATUS.VERIFIKASI_SIMPAN : PENGAJUAN_STATUS.FPK_AO;
}

function afterAnalisa(hasSurvey) {
    return hasSurvey ? WORKFLOW_NEXT_STATUS.REKAP_ANALISA_SIMPAN : PENGAJUAN_STATUS.SURVEY_DEBITUR;
}

function afterMukReview(hasMuk) {
    return hasMuk ? WORKFLOW_NEXT_STATUS.APPROVAL_MUK_SETUJUI : PENGAJUAN_STATUS.MUK;
}

module.exports = {
    PENGAJUAN_STATUS, WORKFLOW_NEXT_STATUS, isDraftSubmission,
    afterVerification, afterAnalisa, afterMukReview,
};
